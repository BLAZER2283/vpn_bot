"""Оплата переводом с подтверждением админом.

Нужна, пока не подключена настоящая платёжка. Строка в БД создаётся только
в момент подтверждения — до этого подтверждать нечего, а держать «висящие»
платежи и потом их чистить незачем.

Идентификатор заявки живёт в callback_data кнопки и служит тем же
provider_payment_id. Повторное нажатие «Зачесть» упрётся в уникальный
индекс и ничего не начислит.
"""

from __future__ import annotations

import secrets

CODE = "manual"
TITLE = "Перевод вручную"
CURRENCY = "RUB"


def new_request_id() -> str:
    """Короткий идентификатор — callback_data ограничена 64 байтами."""
    return secrets.token_hex(4)


def admin_request_text(
    *, user_tg_id: int, username: str | None, plan_title: str, amount: int
) -> str:
    return (
        "<b>Заявка на оплату переводом</b>\n\n"
        f"Пользователь: <code>{user_tg_id}</code> @{username or '—'}\n"
        f"Тариф: {plan_title}\n"
        f"Сумма: {amount}\n\n"
        "Зачесть только после того, как деньги реально пришли."
    )


